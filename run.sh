    success "Created ${ENV_FILE}"
else
    log "Using existing ${ENV_FILE}"
fi

# 3. Add /etc/hosts entry
step "Configuring /etc/hosts"
if ! grep -q "^127.0.0.1 ${DOMAIN}" /etc/hosts 2>/dev/null; then
    log "Adding ${DOMAIN} to /etc/hosts (requires sudo)..."
    echo "127.0.0.1 ${DOMAIN}" | sudo tee -a /etc/hosts >/dev/null
    success "Added ${DOMAIN} to /etc/hosts"
else
    log "${DOMAIN} already in /etc/hosts"
fi

# 4. Stop any existing containers
step "Stopping any existing containers"
$COMPOSE_CMD down --remove-orphans 2>/dev/null || true
success "Cleaned up"

# 5. Build and start
step "Building and starting containers (db, app, cron, caddy)"
$COMPOSE_CMD up --build -d

# 6. Wait for database
step "Waiting for database"
wait_for_health db

# 7. Wait for app
step "Waiting for application"
wait_for_health app

# 8. Wait for caddy
step "Waiting for Caddy (HTTPS)"
wait_for_health caddy

# 9. Run migrations
step "Running database migrations"
$COMPOSE_CMD exec -T app npm run migrate
success "Migrations complete"

# 10. Bootstrap admin
step "Bootstrapping admin account"
$COMPOSE_CMD exec -T app npm run bootstrap:admin
success "Admin bootstrapped"

# 11. Create test accounts
step "Creating test accounts (customer, chef, delivery, admin)"
$COMPOSE_CMD exec -T -e DOQ_ALLOW_TEST_ACCOUNTS=true -e DOQ_TEST_PASSWORD="${TEST_PASSWORD}" app \
    node scripts/bootstrap-test-accounts.js
success "Test accounts created"

# 12. Verify CSRF endpoint
step "Verifying HTTPS endpoint"
sleep 2
