#!/usr/bin/env bash
# ============================================================
# DOQ Local Production Runner
# Runs full stack: MySQL + App + Cron + Caddy (HTTPS)
# Creates test accounts for all roles
# ============================================================

set -euo pipefail

# Colors
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
CYAN='\033[0;36m'
NC='\033[0m' # No Color

# Config
PROJECT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ENV_FILE="${PROJECT_DIR}/.env.production.local"
COMPOSE_FILES="-f ${PROJECT_DIR}/docker-compose.yml -f ${PROJECT_DIR}/docker-compose.production.yml"
DOMAIN="doq.local"
COMPOSE_CMD="docker compose ${COMPOSE_FILES} --env-file ${ENV_FILE}"

# Test Account Config
TEST_PASSWORD="TestAccount123!"
ADMIN_EMAIL="admin@doq.local"
ADMIN_PASS="AdminLocal123!"
ADMIN_TOTP="JBSWY3DPEHPK3PXP"

# ============================================================
# Helper Functions
# ============================================================
log()    { echo -e "${BLUE}[INFO]${NC} $*"; }
success(){ echo -e "${GREEN}[OK]${NC} $*"; }
warn()   { echo -e "${YELLOW}[WARN]${NC} $*"; }
error()  { echo -e "${RED}[ERROR]${NC} $*"; exit 1; }
step()   { echo -e "\n${CYAN}=== $* ===${NC}\n"; }

check_cmd() { command -v "$1" >/dev/null 2>&1 || error "$1 not found. Install it first."; }

wait_for_health() {
    local service="$1"
    local max_attempts=60
    local attempt=0
    log "Waiting for ${service} to be healthy..."
    while [[ $attempt -lt $max_attempts ]]; do
        local health
        health=$($COMPOSE_CMD ps --format json "$service" 2>/dev/null | jq -r '.[0].Health // "unknown"' 2>/dev/null || echo "unknown")
        if [[ "$health" == "healthy" ]]; then
            success "${service} is healthy"
            return 0
        fi
        sleep 2
        ((attempt++))
    done
    error "${service} did not become healthy in time"
}

# ============================================================
# Main
# ============================================================
clear
echo -e "${CYAN}"
cat << 'EOF'
╔══════════════════════════════════════════════════════════╗
║  DOQ - Local Production Runner                          ║
║  MySQL + Express + Cron + Caddy (HTTPS)                 ║
║  Auto-creates test accounts for all roles               ║
╚══════════════════════════════════════════════════════════╝
EOF
echo -e "${NC}"

# 1. Check prerequisites
step "Checking prerequisites"
check_cmd docker
check_cmd docker compose
check_cmd jq
check_cmd openssl
success "All commands available"

# 2. Create .env.production.local if not exists
step "Setting up environment file"
if [[ ! -f "$ENV_FILE" ]]; then
    log "Creating ${ENV_FILE}..."
    cat > "$ENV_FILE" <<'ENVEOF'
